import { describe, expect, it } from 'vitest';
import {
  InvalidPassphraseError,
  KeyEncryptedError,
  KeyParseError,
  parsePrivateKey,
  UnsupportedError,
} from '../src';
import { fixture } from './helpers';

// Private key of putty/ed25519.ppk as exported by PuTTY
const ED25519_SEED = '9e15dab1a401c1870509eca660eb589f729dc5c0849462e0d784d85b106f4c4c';

describe('PuTTY private keys', () => {
  const cases = [
    { name: 'rsa', type: 'rsa', comment: 'rsa-key-20210515', passphrase: 'foobar' },
    { name: 'ecdsa', type: 'ecdsa', comment: 'ecdsa-key-20210515', passphrase: 'foobar' },
    { name: 'ed25519', type: 'ed25519', comment: 'ed25519-key-20210515', passphrase: 'foobar' },
    { name: 'rsa-v3', type: 'rsa', comment: 'rsa-key-20211214', passphrase: undefined },
  ];

  for (const c of cases) {
    it(`parses ${c.name}.ppk generated by PuTTY`, () => {
      const key = parsePrivateKey(fixture(`putty/${c.name}.ppk`), { passphrase: c.passphrase });
      expect(key.type).toBe(c.type);
      expect(key.comment).toBe(c.comment);
      if (c.name === 'ed25519') {
        expect(Buffer.from(key.toJwk().d as string, 'base64url').toString('hex')).toBe(ED25519_SEED);
        return;
      }
      // The same keys exported from PuTTY as PEM
      const reference = parsePrivateKey(fixture(`putty/${c.name}.pem`));
      expect(key.equals(reference)).toBe(true);
      expect(key.toJwk().d).toBe(reference.toJwk().d);
    });
  }

  it('reproduces the PuTTY files byte for byte', () => {
    // PPK output is deterministic, so writing a parsed key must give back the original file.
    for (const c of cases) {
      const original = fixture(`putty/${c.name}.ppk`);
      const key = parsePrivateKey(original, { passphrase: c.passphrase });
      const written = key.toString('putty', {
        passphrase: c.passphrase,
        ppkVersion: c.name === 'rsa-v3' ? 3 : 2,
      });
      expect(written.replace(/\r\n/g, '\n')).toBe(original.replace(/\r\n/g, '\n'));
    }
  });

  it('handles passphrases', () => {
    const text = fixture('putty/ed25519.ppk');
    expect(() => parsePrivateKey(text)).toThrow(KeyEncryptedError);
    expect(() => parsePrivateKey(text, { passphrase: 'wrong' })).toThrow(InvalidPassphraseError);
  });

  it('detects tampering through the MAC', () => {
    const text = fixture('putty/rsa-v3.ppk');
    expect(() => parsePrivateKey(text.replace('rsa-key-20211214', 'rsa-key-20211215'))).toThrow(/MAC/);
    expect(() => parsePrivateKey(text.split('\n').slice(0, 5).join('\n'))).toThrow(KeyParseError);
  });

  it('does not support encrypted version 3 files', () => {
    const key = parsePrivateKey(fixture('putty/rsa-v3.ppk'));
    expect(() => key.toString('putty', { ppkVersion: 3, passphrase: 'pw' })).toThrow(UnsupportedError);
    const encryptedV3 = fixture('putty/rsa-v3.ppk').replace('Encryption: none', 'Encryption: aes256-cbc');
    expect(() => parsePrivateKey(encryptedV3, { passphrase: 'pw' })).toThrow(UnsupportedError);
  });

  it('converts OpenSSH keys to PPK and back', () => {
    for (const name of ['ed25519', 'rsa', 'ecdsa256']) {
      const key = parsePrivateKey(fixture(`openssh/${name}`));
      for (const ppkVersion of [2, 3] as const) {
        const back = parsePrivateKey(key.toString('putty', { ppkVersion }));
        expect(back.equals(key)).toBe(true);
        expect(back.comment).toBe(key.comment);
      }
      const encrypted = key.toString('putty', { passphrase: 'pw' });
      expect(parsePrivateKey(encrypted, { passphrase: 'pw' }).toString('pkcs8')).toBe(key.toString('pkcs8'));
    }
  });
});
