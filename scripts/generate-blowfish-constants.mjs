// Generates src/internal/blowfish-constants.ts.
// The Blowfish initial P-array and S-boxes are the fractional hexadecimal
// digits of pi, so they are computed here instead of being typed in by hand.
import { writeFileSync } from 'node:fs';

const WORDS = 18 + 4 * 256;
const BITS = WORDS * 32;
const GUARD = 64;
const ONE = 1n << BigInt(BITS + GUARD);

function arctanInverse(x) {
  // arctan(1/x) in fixed point
  const x2 = BigInt(x) * BigInt(x);
  let term = ONE / BigInt(x);
  let sum = term;
  let n = 1n;
  let sign = -1n;
  while (term !== 0n) {
    term /= x2;
    n += 2n;
    sum += (sign * term) / n;
    sign = -sign;
  }
  return sum;
}

// Machin: pi = 16 arctan(1/5) - 4 arctan(1/239)
const pi = 16n * arctanInverse(5) - 4n * arctanInverse(239);
const fraction = (pi - 3n * ONE) >> BigInt(GUARD);
const hex = fraction.toString(16).padStart(BITS / 4, '0');

const words = [];
for (let i = 0; i < WORDS; i++) words.push('0x' + hex.slice(i * 8, i * 8 + 8));

function rows(list) {
  const out = [];
  for (let i = 0; i < list.length; i += 6) out.push('  ' + list.slice(i, i + 6).join(', ') + ',');
  return out.join('\n');
}

const source = `// Generated by scripts/generate-blowfish-constants.mjs. Do not edit.
// Blowfish initial state: the fractional hexadecimal digits of pi.

export const INITIAL_P: readonly number[] = [
${rows(words.slice(0, 18))}
];

export const INITIAL_S: readonly number[] = [
${rows(words.slice(18))}
];
`;

writeFileSync(new URL('../src/internal/blowfish-constants.ts', import.meta.url), source);
console.log(`wrote ${WORDS} words; P[0]=${words[0]} S[last]=${words[WORDS - 1]}`);
